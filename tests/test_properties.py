finite = st.floats(min_value=-1e9, max_value=1e9, allow_nan=False, allow_infinity=False)


@settings(max_examples=300, deadline=None)
@given(hnp.arrays(np.float64, st.integers(0, 1500), elements=finite), st.integers(0, 9))
def test_pairwise_sum_equals_numpy(values: np.ndarray, offset: int) -> None:
    """The Numba port reproduces NumPy's pairwise summation bit for bit, for any length and start."""
    padded = np.concatenate([np.ones(offset), values])
    assert _pairwise_sum(padded, offset, len(values)) == np.add.reduce(padded[offset:].copy())


@st.composite
def minute_bars(draw: st.DrawFn) -> pd.DataFrame:
    n = draw(st.integers(1, 400))
    present = draw(hnp.arrays(np.bool_, n, elements=st.booleans()))
    present[0] = True
    start = pd.Timestamp("2024-01-01", tz="UTC") + pd.Timedelta(minutes=draw(st.integers(0, 2000)))
    ts = pd.date_range(start, periods=n, freq="1min")[present]
    k = len(ts)
    opens = draw(hnp.arrays(np.float64, k, elements=st.floats(1, 1e5)))
    closes = draw(hnp.arrays(np.float64, k, elements=st.floats(1, 1e5)))
    spread = draw(hnp.arrays(np.float64, k, elements=st.floats(0, 100)))
    return pd.DataFrame(
        {
            "ts": ts,
            "open": opens,
            "high": np.maximum(opens, closes) + spread,
            "low": np.minimum(opens, closes) - spread / 2,
            "close": closes,
            "volume": draw(hnp.arrays(np.float64, k, elements=st.floats(0, 1e6))),
            "source": "s",
            "symbol": "x",
        }
    )


@settings(max_examples=100, deadline=None)
@given(minute_bars(), st.sampled_from(["5m", "15m", "1h", "4h", "1d"]))
def test_resample_invariants(bars: pd.DataFrame, timeframe: str) -> None:
    out = resample_bars(bars, timeframe)
    assert out["n_minutes"].sum() == len(bars)
    assert math.isclose(out["volume"].sum(), bars["volume"].sum(), rel_tol=1e-9, abs_tol=1e-6)
    assert out["high"].max() == bars["high"].max()
    assert out["low"].min() == bars["low"].min()
    assert out["open"].iloc[0] == bars["open"].iloc[0]
    assert out["close"].iloc[-1] == bars["close"].iloc[-1]
    assert (out["high"] >= out[["open", "close"]].max(axis=1)).all()
    assert (out["low"] <= out[["open", "close"]].min(axis=1)).all()
    assert out["ts"].is_monotonic_increasing
    assert (out["ts"] == out["ts"].dt.floor(TIMEFRAMES[timeframe])).all()


@st.composite
def tuned_spec(draw: st.DrawFn) -> StrategySpec:
    spec = draw(st.sampled_from(SPECS))
    values = {}
    for p in tunable_parameters(spec):
        if p.path[0] == "rules":
            continue  # rule constants keep their meaning (and the validator's range checks) only near their values
        if p.integer:
            values[p.name] = float(draw(st.integers(int(p.low), int(min(p.high, 400)))))
        else:
            values[p.name] = draw(st.floats(p.low, min(p.high, 1e4), allow_nan=False))
    return with_params(spec, values)


@settings(max_examples=150, deadline=None)
@given(tuned_spec())
def test_transport_round_trip(spec: StrategySpec) -> None:
    """Whatever the parameters, the transport form converts back to the identical spec."""
    canonical, issues = from_transport(to_transport(spec))
    assert issues == []
    assert StrategySpec.model_validate(canonical) == spec


@settings(max_examples=150, deadline=None)
@given(tuned_spec(), tuned_spec())
def test_spec_diff_is_empty_exactly_for_equal_specs(a: StrategySpec, b: StrategySpec) -> None:
    assert (spec_diff(a, b) == []) == (a == b)
    assert spec_diff(a, a) == []


@settings(max_examples=300, deadline=None)
@given(
    hnp.arrays(
        np.float64,
        hnp.array_shapes(min_dims=2, max_dims=2, min_side=1, max_side=9),
        elements=st.one_of(st.floats(-5, 5), st.just(-math.inf)),
    ),
    st.data(),
)
def test_heatmap_stability_is_a_share(matrix: np.ndarray, data: st.DataObject) -> None:
    row = data.draw(st.integers(0, matrix.shape[0] - 1))
    col = data.draw(st.integers(0, matrix.shape[1] - 1))
    value = stability_at(matrix, row, col)
    assert 0.0 <= value <= 1.0
    if not matrix[row, col] > 0:
        assert value == 0.0


@settings(max_examples=200, deadline=None)
@given(hnp.arrays(np.float64, st.integers(1, 300), elements=st.floats(1.0, 1e6)))
def test_drawdown_bounds(values: np.ndarray) -> None:
    equity = pd.Series(values, index=pd.date_range("2024-01-01", periods=len(values), freq="1h", tz="UTC"))
    worst, days = drawdown(equity)
    assert -100.0 < worst <= 0.0
    assert 0.0 <= days <= (len(values) - 1) / 24
    if np.all(np.diff(values) >= 0):
        assert worst == 0.0
        assert days == 0.0
